const generatedTermKeys = Object.keys(musicLabels)
  .filter((key) => /[\p{Script=Han}]/u.test(key))
  .sort((a, b) => b.length - a.length);

/** Translate only known display tokens and generated summaries, never arbitrary substrings in user names. */
export function translateMusicLabel(text: string, lang = "ru"): string {
  if (lang !== "ru") return text;
  if (musicLabels[text]) return musicLabels[text];
  if (/^Pattern \d+$/.test(text)) return text.replace("Pattern", "Паттерн");
  if (/^Track \d+$/.test(text)) return text.replace("Track", "Дорожка");
  if (text.includes(" · "))
    return text
      .split(" · ")
      .map((part) => translateMusicLabel(part, lang))
      .join(" · ");
  // Generated key/cadence/motif summaries can concatenate known Chinese theory terms.
  if (/[\p{Script=Han}]/u.test(text))
    return generatedTermKeys.reduce(
      (value, key) => value.split(key).join(musicLabels[key]),
      text,
    );
  return text;
}
